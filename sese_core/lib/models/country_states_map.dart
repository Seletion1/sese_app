/// Returns the list of states/regions for the given ISO alpha-2 country code,
/// or an empty list if the country is not in the map.
List<String> statesForCountry(String? countryCode) {
  if (countryCode == null || countryCode.isEmpty) return const [];
  return kCountryToStatesMap[countryCode.toUpperCase()] ?? const [];
}
